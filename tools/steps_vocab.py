"""Generate docs/step_vocabulary.md: the distinct step phrases the specification uses.

Reviewers check the domain language; implementers bind these phrases at G4.
Quoted values and outline placeholders are shown as "{}" and <>.
Usage: python tools/steps_vocab.py
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from arch import ROOT

FEATURES = ROOT / "specs/features"
OUT = ROOT / "docs/step_vocabulary.md"


def main():
    from behave.parser import parse_file

    phrases = defaultdict(set)
    for f in sorted(FEATURES.glob("*.feature")):
        feature = parse_file(str(f))
        scenarios = ([feature.background] if feature.background else []) + list(feature.scenarios)
        for sc in scenarios:
            for st in sc.steps:
                text = re.sub(r'"[^"]*"', '"{}"', st.name)
                phrases[(st.step_type, text)].add(f.name)
    lines = ["# Step vocabulary", "",
             "Generated by `python tools/steps_vocab.py`; do not edit. Distinct step phrases of `specs/features/`.", ""]
    for kind in ("given", "when", "then"):
        items = sorted(t for (k, t) in phrases if k == kind)
        lines += [f"## {kind.capitalize()} ({len(items)})", ""]
        lines += [f"- {t}" for t in items] + [""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(phrases)} phrases")


if __name__ == "__main__":
    main()
